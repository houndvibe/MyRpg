type Pt = [number, number];
interface Rect {
  x: number;
  y: number;
  w: number;
  h: number;
}

/**
 * Атмосфера карты (components/MapAmbience.ts): что включено и где — в пикселях подложки. Нет поля — эффекта нет.
 * chimneys — трубы с нарисованным дымом; windows — светящиеся окна и фонари; pond — участок воды для ряби (прямоугольник);
 * fog — полосы тумана; clouds — тени облаков; cloudLayer — полупрозрачные облака над картой (ближе к камере);
 * birdsY — коридор пролёта птиц по высоте; snow — снегопад на экране; aurora — где переливается северное сияние;
 * wisps — болотные огоньки; embers — костры с искрами; rivers — где искать воду для бликов (вода находится по цвету).
 */
export interface AmbienceProfile {
  chimneys?: Pt[];
  windows?: Pt[];
  pond?: Rect;
  fog?: Rect[];
  clouds?: boolean;
  cloudLayer?: boolean;
  birdsY?: Pt;
  snow?: boolean;
  aurora?: Rect;
  wisps?: Pt[];
  embers?: Pt[];
  rivers?: Rect;
}

