// Карты игрового режима: локации (у каждой своя подложка, точки интереса и дороги) и карта мира между ними (data/world.ts).
// Координаты — в пикселях подложки своей локации; на экране карта увеличена (MAP_LAYOUT.locations[…].scale в assets.ts).
// Развилки — служебные узлы дорог, игрок туда не ходит. У каждой локации есть точка выхода (exit) на краю карты —
// через неё герой уходит на карту мира и приходит из неё.

export type LocationId = 'zastava' | 'chasha' | 'severland';
/** Локации с медальоном на карте мира (у остальных есть parent — они часть другой локации). */
export type WorldLocationId = Exclude<LocationId, 'chasha'>;

/** Застава. */
type ZastavaPoi =
  | 'gate' | 'inn' | 'market' | 'mayor' | 'church' | 'pogost' | 'lodge'
  | 'summit' | 'warden' | 'camp' | 'pond' | 'thicket' | 'mill' | 'tract';
/** Северляндия. */
type SeverlandPoi =
  | 's_cross' | 's_fishers' | 's_kremlin' | 's_harbor' | 's_elder' | 's_forge'
  | 's_stones' | 's_skete' | 's_camp' | 's_rotten' | 's_south';
/** Чаща — лес за Трактом Заставы, вторая карта Заставы. */
type ChashaPoi = 'c_carriage' | 'c_hut' | 'c_pond' | 'c_tree' | 'c_den' | 'c_edge';
export type PoiId = ZastavaPoi | ChashaPoi | SeverlandPoi;

export interface Poi {
  id: PoiId;
  loc: LocationId;
  /** Название — видно при наведении и в надписи «Вы здесь». Рабочее, правится свободно. */
  name: string;
  x: number;
  y: number;
  /** Пояс — удалённость от ночлега по дороге: надбавка к цене действий в свечах (BELT_CANDLES в balance.ts). Нет — 0.
   *  Задаётся вручную: стартовая разметка Заставы — по длине дороги от постоялого двора (docs/gameplay.md). */
  belt?: number;
}

/** Участок дороги между двумя узлами (точкой или развилкой): ломаная от a до b включительно. */
export interface Road {
  a: string;
  b: string;
  points: [number, number][];
}

export interface LocationDef {
  id: LocationId;
  name: string;
  /** Где герой появляется при первом входе в игровой режим (важно только у стартовой локации). */
  start: PoiId;
  /** Точка выхода на карту мира (на краю карты, где дорога уходит за край). */
  exit: PoiId;
  /** Ночлег: здесь спят (комнаты, новая ночь) и только отсюда уезжают («Отдохнуть и в дорогу…»). Нет — ночлега в локации
   *  ещё нет: цена действий без поясов, в путь — из точки выхода и клавишей M, как раньше. */
  lodging?: PoiId;
  /** Часть другой локации (Чаща — Заставы): своего медальона на карте мира нет, на карте мира герой — в parent. */
  parent?: WorldLocationId;
  /** Ворота города: пока герой первый раз не прошёл через них, в локации звучит музыка Чащи (run.gatePassed). */
  gate?: PoiId;
  /** Куда герой приходит с карты мира. Нет — в точку выхода (exit). */
  arrival?: PoiId;
  /** Переходы на соседнюю карту той же локации пешком (затемнение, без карты мира): из точки from — в точку at карты to. */
  links?: { from: PoiId; to: LocationId; at: PoiId; label: string }[];
  junctions: Record<string, { x: number; y: number }>;
  /** Зоны свободного хода (многоугольники, пиксели подложки): внутри герой ходит куда угодно, вход и выход — с тропы. */
  free?: [number, number][][];
  roads: Road[];
}

