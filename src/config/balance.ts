// ─── Соседство ───────────────────────────────────────────────────────────────
// Соседи — предметы, у которых хотя бы одна клетка касается стороной клетки другого (без диагоналей).
// Сами правила (кто на кого и как действует) — в src/data/synergies.ts, здесь только числа.
// Формула (гайд, 1.2): итог = база × (1 + Σ «увеличение»), не ниже 0. Все бонусы соседства — «увеличение»: складываются
// в одну сумму. Плоских бонусов и «множителей» сейчас нет; новый вид бонуса обязан попасть в один из этих трёх ящиков.
// Правила стака (гайд, 2.1): бонус — за предмет-соседа, не за клетку; одинаковые ауры (одно правило) не складываются —
// работает сильнейшая; на предмет действуют не больше SYNERGY_STACK.maxAuras сильнейших бонусов; аура не усиливает
// ауру; сумма бонусов проходит через страховочный кап SYNERGY_STACK.
// Отключение сильнее любых бонусов. Отключённый предмет сам ни на кого не влияет.

