/** Подложка карты: ключ и путь, увеличение (scale × размер картинки = размер мира карты), атмосфера. */
/**
 * Заслон на карте (здание, дерево): при загрузке вырезается из подложки по контуру poly (пиксели подложки) и кладётся поверх
 * карты на то же место. baseY — основание: выше него герой за заслоном; pivot — точка, вокруг которой дерево качается
 * (нет — середина по x на baseY). trunk — ствол-препятствие (круг; герой его обходит, задел — дерево качнулось).
 * trim — вырезать без тумана вокруг (светлые серо-голубые пиксели); 'leafy' — оставить только листву и кору (лиственные деревья:
 * тёмный фон между ветвями — не дерево). leaves — цвет листьев, что падают с задетого дерева.
 * hover — подсвечивать при наведении мыши (когда заслон уже открыт из-под тумана войны); poi — точка, куда идёт герой по клику на заслон.
 */
export interface MapOccluder {
  poly: [number, number][];
  baseY: number;
  pivot?: [number, number];
  trunk?: { x: number; y: number; r: number };
  trim?: boolean | 'leafy';
  leaves?: number;
  hover?: boolean;
  poi?: PoiId;
}

/** Ель — заслон-треугольник: макушка (x, tipY), основание baseY, полуширина нижних лап hw (пиксели подложки). */
function fir(x: number, tipY: number, baseY: number, hw: number): MapOccluder {
  return { poly: [[x, tipY], [x + hw, baseY - 12], [x + hw * 0.35, baseY], [x - hw * 0.35, baseY], [x - hw, baseY - 12]], baseY, pivot: [x, baseY], trunk: { x, y: baseY - 3, r: 5 }, trim: true };
}

/** Лиственное дерево (берёза) — крона-эллипс (cx, cy, rx, ry) и ствол до основания (bx, by) полушириной tw; leaves — цвет листьев. */
function leafy(cx: number, cy: number, rx: number, ry: number, bx: number, by: number, tw: number, leaves: number): MapOccluder {
  // Крона по кругу снизу-слева через верх вниз-направо, затем ствол прямо вниз — узкий, чтобы рядом со стволом героя не закрывал фон.
  const neck = Math.round(cy + ry * 0.9);
  const poly: [number, number][] = [[bx - tw, neck]];
  for (let a = 110; a <= 430; a += 15) poly.push([Math.round(cx + rx * Math.cos((a * Math.PI) / 180)), Math.round(cy + ry * Math.sin((a * Math.PI) / 180))]);
  poly.push([bx + tw, neck], [bx + tw, by], [bx - tw, by]);
  return { poly, baseY: by, pivot: [bx, by], trunk: { x: bx, y: by - 3, r: tw + 3 }, trim: 'leafy', leaves };
}

